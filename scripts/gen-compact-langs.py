#!/usr/bin/env python3
"""Generate the Rust language table of `ai-gent compact` from `langs.py` (spec 037 FR-D2, T063).

  python3 scripts/gen-compact-langs.py           write the table and the --list-languages golden
  python3 scripts/gen-compact-langs.py --check   exit 1 when either file is out of date

Writes `rust/crates/ai-gent-compact/src/data/compact-langs.rs` (meant for `include!` into the `ai-gent-compact` crate,
whose `langs.rs` defines `struct LangSpec` with these fields) and `rust/fixtures/compact/list-languages.golden`
(the exact `compact.py --list-languages` output, for the Rust command's parity test).
Both go away with `langs.py` at the 3.0.0 cutover; the table then becomes the source.

Flag bits: blank 1, indent 2, join 4, spaces 8. Regex fields are copied verbatim as raw strings. The
`regex` crate has no look-around or back-references, so a pattern that uses them is marked in
`needs_lookaround`; the consumer must hand-write those (csharp `protect`, scss and less `hazard`).
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGS_PY = ROOT / "plugins/compact/skills/code/scripts/langs.py"
DATA = ROOT / "rust/crates/ai-gent-compact/src/data/compact-langs.rs"
GOLDEN = ROOT / "rust/fixtures/compact/list-languages.golden"
BITS = {"blank": 1, "indent": 2, "join": 4, "spaces": 8}
LEVEL_NAMES = {0: "as-is", 1: "blank", 2: "lines", 3: "flat", 4: "dense"}


def load():
    spec = importlib.util.spec_from_file_location("compact_langs_src", LANGS_PY)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def bits(flags):
    return sum(BITS[f] for f in flags)


def level_of(mod, flags):
    for lv in (4, 3, 2, 1):
        if mod.LEVELS[lv] <= flags:
            return lv
    return 0


def raw(s):
    """A Rust raw string literal holding `s`."""
    n = 0
    while '"' + "#" * n in s:
        n += 1
    return 'r%s"%s"%s' % ("#" * n, s, "#" * n)


def opt(v):
    return "None" if v is None else "Some(%s)" % raw(v)


def lookaround(pattern):
    return pattern is not None and any(t in pattern for t in ("(?<", "(?=", "(?!", "\\1"))


def rust_text(mod):
    out = ["// @generated by scripts/gen-compact-langs.py from langs.py. Do not edit.", "//",
           "// Fields: key, extensions, exact file names, allowed flag bits (blank 1, indent 2, join 4,",
           "// spaces 8), join rule, preprocessor lines, tree-sitter name, tree-sitter verification,",
           "// protect pattern, hazard pattern, flag bits under the hazard, indent-sensitive,",
           "// needs_lookaround (a pattern the regex crate cannot compile).",
           "&["]
    for key in sorted(mod.LANGS):
        s = mod.LANGS[key]
        out.append("    LangSpec {")
        out.append("        key: %s," % raw(key))
        out.append("        exts: &[%s]," % ", ".join(raw(e) for e in s["exts"]))
        out.append("        names: &[%s]," % ", ".join(raw(n) for n in s["names"]))
        out.append("        allowed: %d," % bits(s["allowed"]))
        out.append("        join: %s," % ("None" if s["join"] is None else "Some(%s)" % raw(s["join"])))
        out.append("        preproc: %s," % str(s["preproc"]).lower())
        out.append("        ts: %s," % opt(s["ts"]))
        out.append("        ts_verify: %s," % opt(s["ts_verify"]))
        protect = s["protect"].pattern if s["protect"] else None
        hazard = s["hazard"].pattern if s["hazard"] else None
        out.append("        protect: %s," % opt(protect))
        out.append("        hazard: %s," % opt(hazard))
        out.append("        hazard_allowed: %d," % bits(s["hazard_allowed"]))
        out.append("        indent_sensitive: %s," % str(s["indent_sensitive"]).lower())
        out.append("        needs_lookaround: %s," % str(lookaround(protect) or lookaround(hazard)).lower())
        out.append("    },")
    out.append("]")
    return "\n".join(out) + "\n"


def golden_text(mod):
    """The output of `compact.py --list-languages`."""
    rows = []
    for key in sorted(mod.LANGS):
        s = mod.LANGS[key]
        lv = level_of(mod, s["allowed"])
        rows.append("%-12s max L%d (%s)%s  %s" % (key, lv, LEVEL_NAMES[lv],
                                                  "  indent-sensitive" if s["indent_sensitive"] else "",
                                                  " ".join(s["exts"] + s["names"])))
    return "\n".join(rows) + "\n"


def expected():
    mod = load()
    return {DATA: rust_text(mod), GOLDEN: golden_text(mod)}


def stale(root_langs_present=True):
    """Paths whose content differs from what `langs.py` generates."""
    if not LANGS_PY.is_file():
        return []
    return [str(p.relative_to(ROOT)) for p, text in expected().items()
            if not p.is_file() or p.read_text(encoding="utf-8") != text]


def main(argv):
    if "--check" in argv:
        bad = stale()
        for p in bad:
            print("FAIL  %s is out of date (run python3 scripts/gen-compact-langs.py)" % p)
        return 1 if bad else 0
    for path, text in expected().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
