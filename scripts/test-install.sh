#!/usr/bin/env bash
# Tests setup.sh and install.sh in a throwaway HOME: install, idempotent
# re-run, dry run, pruning, the opencode symlink replacement, the agent choice
# (Claude Code by default, the rest opt-in and remembered), the generated
# entries for agents without plugin namespaces, uninstall, and that
# directories the scripts didn't create are left alone. Called by
# scripts/check.sh.

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SANDBOX="$(mktemp -d)"
trap 'rm -rf "$SANDBOX"' EXIT

export HOME="$SANDBOX/home"
export CLAUDE_SKILLS_DIR="$HOME/.claude/skills"
export OPENCODE_SKILLS_DIR="$HOME/.config/opencode/skills"
export OPENCODE_COMMANDS_DIR="$HOME/.config/opencode/commands"
export AGENTS_SKILLS_DIR="$HOME/.agents/skills"
export KIRO_SKILLS_DIR="$HOME/.kiro/skills"
export WINDSURF_SKILLS_DIR="$HOME/.codeium/windsurf/skills"
export XDG_STATE_HOME="$HOME/.local/state"
targets_state="$XDG_STATE_HOME/ai-gent/targets"
unset XDG_DATA_HOME AI_GENT_DIR AI_GENT_REPO AI_GENT_BRANCH

failures=0
check() { # check <description> <command...>
  local what="$1"
  shift
  if "$@"; then
    printf '      ok    %s\n' "$what"
  else
    printf '      FAIL  %s\n' "$what"
    failures=$((failures + 1))
  fi
}

setup() { # a failure shows setup.sh's output instead of aborting silently
  "$REPO_DIR/setup.sh" "$@" >"$SANDBOX/out" 2>&1 || {
    local rc=$?
    echo "setup.sh $* failed ($rc):" >&2
    cat "$SANDBOX/out" >&2
    return "$rc"
  }
}
# Path, mode, size, mtime and link target of everything under HOME (portable:
# GNU ls and find options are missing on macOS).
snapshot() {
  python3 - "$HOME" <<'PY'
import os, sys
root = sys.argv[1]
for dirpath, dirs, files in os.walk(root):
    dirs.sort()
    for name in sorted(dirs + files):
        p = os.path.join(dirpath, name)
        st = os.lstat(p)
        print(p, oct(st.st_mode), st.st_size, st.st_mtime_ns, os.readlink(p) if os.path.islink(p) else "")
PY
}
# links_into <dir> <prefix> — how many symlinks directly in <dir> point under <prefix>
links_into() {
  python3 - "$1" "$2" <<'PY'
import os, sys
d, prefix = sys.argv[1:3]
print(sum(1 for n in os.listdir(d) if os.path.islink(os.path.join(d, n)) and os.readlink(os.path.join(d, n)).startswith(prefix + "/")))
PY
}

count() { { find "$@" 2>/dev/null || true; } | wc -l; }
skills=$(count "$REPO_DIR/skills" -mindepth 2 -maxdepth 2 -name SKILL.md)
plugins=$(count "$REPO_DIR/plugins" -mindepth 3 -maxdepth 3 -path '*/.claude-plugin/plugin.json')
plugin_skills=$(count "$REPO_DIR/plugins" -mindepth 4 -maxdepth 4 -path '*/skills/*/SKILL.md')

# Things the user owns, which must survive everything below.
mkdir -p "$CLAUDE_SKILLS_DIR/mine" "$CLAUDE_SKILLS_DIR/synced/one" "$OPENCODE_COMMANDS_DIR"
echo "own" >"$CLAUDE_SKILLS_DIR/mine/SKILL.md"
echo "own" >"$OPENCODE_COMMANDS_DIR/mine.md"
# A symlink from opencode's skills dir to Claude's, which setup.sh replaces.
mkdir -p "$(dirname "$OPENCODE_SKILLS_DIR")"
ln -s "$CLAUDE_SKILLS_DIR" "$OPENCODE_SKILLS_DIR"

echo "      -- dry run"
before="$(snapshot)"
setup --dry-run
check "changes nothing" test "$before" == "$(snapshot)"

echo "      -- install"
setup --target claude,opencode
check "the choice is remembered" test "$(cat "$targets_state")" == "claude opencode"
check "claude: one link per skill and plugin" test "$(links_into "$CLAUDE_SKILLS_DIR" "$REPO_DIR")" -eq $((skills + plugins))
check "opencode: skills dir is now a real directory" test ! -L "$OPENCODE_SKILLS_DIR" -a -d "$OPENCODE_SKILLS_DIR"
check "opencode: one link per personal skill" test "$(links_into "$OPENCODE_SKILLS_DIR" "$REPO_DIR")" -eq "$skills"
check "opencode: synced linked" test -L "$OPENCODE_SKILLS_DIR/synced"
check "opencode: one generated entry per plugin skill" \
  test "$(find "$OPENCODE_SKILLS_DIR" -mindepth 2 -maxdepth 2 -name .ai-gent-generated | wc -l)" -eq "$plugin_skills"
check "opencode: one generated command per plugin skill" \
  test "$(grep -l 'Generated by ai-gent/setup.sh' "$OPENCODE_COMMANDS_DIR"/*.md | wc -l)" -eq "$plugin_skills"
check "opencode: a forked skill's command runs as a subtask" grep -qx 'subtask: true' "$OPENCODE_COMMANDS_DIR/devsecops-watch.md"
check "opencode: other commands stay in the main context" bash -c '! grep -q "^subtask:" "$1"' _ "$OPENCODE_COMMANDS_DIR/project-init.md"
check "generated entries point at existing sources" bash -c '
  for f in "$1"/*/SKILL.md; do
    [[ -f "$(dirname "$f")/.ai-gent-generated" ]] || continue
    src=$(sed -n "s/^  source: \"\(.*\)\"$/\1/p" "$f"); [[ -f "$src" ]] || exit 1
  done' _ "$OPENCODE_SKILLS_DIR"

echo "      -- re-run"
setup
check "idempotent (nothing linked or generated)" bash -c '! grep -Eq "^\[(link|relink|generate|backup)\] " "$1"' _ "$SANDBOX/out"
check "summary: every claude skill and plugin ok" grep -Eq "^\[ok\] +\[$((skills + plugins))/$((skills + plugins))\]\$" "$SANDBOX/out"
check "summary: no per-item lines without a terminal" bash -c '! grep -Eq "^\[ok\] +[a-z]+\$" "$1"' _ "$SANDBOX/out"
check "no colors without a terminal" bash -c '! grep -q $'"'"'\e'"'"' "$1"' _ "$SANDBOX/out"
setup --verbose
check "--verbose: one line per item" grep -Eq "^ok +qa\$" "$SANDBOX/out"
if script --version 2>/dev/null | grep -q util-linux; then # a terminal, via util-linux script
  TERM=xterm-256color script -qec "$REPO_DIR/setup.sh --skip-prompt --no-config-edits" /dev/null >"$SANDBOX/out" 2>&1
  check "terminal: progress rewritten in place" grep -q $'\r\e\[K' "$SANDBOX/out"
  check "terminal: colored statuses" grep -q $'\e\[32m\[ok\]' "$SANDBOX/out"
  NO_COLOR=1 TERM=xterm-256color script -qec "$REPO_DIR/setup.sh --skip-prompt --no-config-edits" /dev/null >"$SANDBOX/out" 2>&1
  check "terminal: NO_COLOR turns colors off" bash -c '! grep -q $'"'"'\e\[3[0-9]m'"'"' "$1"' _ "$SANDBOX/out"
fi

echo "      -- prune"
ln -s "$REPO_DIR/plugins/gone" "$CLAUDE_SKILLS_DIR/gone"
mkdir -p "$OPENCODE_SKILLS_DIR/gone-skill"
printf -- '---\nname: gone-skill\nmetadata:\n  source: "%s"\n---\n' "$REPO_DIR/plugins/gone/skills/skill/SKILL.md" \
  >"$OPENCODE_SKILLS_DIR/gone-skill/SKILL.md"
touch "$OPENCODE_SKILLS_DIR/gone-skill/.ai-gent-generated"
echo "<!-- Generated by ai-gent/setup.sh. -->" >"$OPENCODE_COMMANDS_DIR/gone-skill.md"
setup
check "stale claude link removed" test ! -L "$CLAUDE_SKILLS_DIR/gone"
check "stale opencode entry and command removed" test ! -e "$OPENCODE_SKILLS_DIR/gone-skill" -a ! -e "$OPENCODE_COMMANDS_DIR/gone-skill.md"

echo "      -- skip without --force"
rm "$CLAUDE_SKILLS_DIR/qa"
mkdir "$CLAUDE_SKILLS_DIR/qa"
setup
check "real directory in the way is kept" test -d "$CLAUDE_SKILLS_DIR/qa" -a ! -L "$CLAUDE_SKILLS_DIR/qa"
check "the skip and its reason are reported" bash -c 'grep -Eq "^\[skip\] +\[1/[0-9]+\] +qa\$" "$1" && grep -q "qa: real file or directory in the way" "$1"' _ "$SANDBOX/out"
setup --force
check "--force backs it up and links" bash -c 'test -L "$1/qa" && compgen -G "$1/qa.bak-*" >/dev/null' _ "$CLAUDE_SKILLS_DIR"
rm -rf "$CLAUDE_SKILLS_DIR"/qa.bak-*

echo "      -- other agents"
gen_count() { find "$1" -mindepth 2 -maxdepth 2 -name .ai-gent-generated 2>/dev/null | wc -l; }
setup --target claude,codex,cursor,kiro
check "codex and cursor: one shared entry per skill and plugin skill" test "$(gen_count "$AGENTS_SKILLS_DIR")" -eq $((skills + plugin_skills))
check "shared entries are files, not symlinks" test "$(find "$AGENTS_SKILLS_DIR" -maxdepth 1 -type l | wc -l)" -eq 0
check "one section for the agents sharing ~/.agents/skills" grep -q "^== Codex, Cursor:" "$SANDBOX/out"
check "kiro: its own entries" test "$(gen_count "$KIRO_SKILLS_DIR")" -eq $((skills + plugin_skills))
check "windsurf: untouched when not chosen" test ! -e "$WINDSURF_SKILLS_DIR"
check "the guard gap is noted" grep -q "guards are instructions only" "$SANDBOX/out"
check "entries say which agent, not opencode" bash -c '! grep -q "opencode" "$1"/db-inspect/SKILL.md' _ "$AGENTS_SKILLS_DIR"
check "the new choice is remembered" test "$(cat "$targets_state")" == "claude codex cursor kiro"
setup --skip-prompt
check "--skip-prompt: the remembered choice, unchanged" bash -c '! grep -Eq "^\[(link|generate)\] " "$1" && grep -q "^== Kiro:" "$1"' _ "$SANDBOX/out"
setup --uninstall --target kiro
check "--uninstall --target: only that agent" test "$(gen_count "$KIRO_SKILLS_DIR")" -eq 0 -a "$(gen_count "$AGENTS_SKILLS_DIR")" -gt 0
check "--uninstall --target: forgotten" test "$(cat "$targets_state")" == "claude codex cursor"
setup --uninstall --target codex
check "--uninstall --target: shared entries kept while another agent uses them" test "$(gen_count "$AGENTS_SKILLS_DIR")" -gt 0
check "--uninstall --target: the keeper is named" grep -q "kept: Cursor still uses it" "$SANDBOX/out"
setup --uninstall --target cursor
check "--uninstall --target: shared entries removed with the last agent" test "$(gen_count "$AGENTS_SKILLS_DIR")" -eq 0
setup --target claude,codex,cursor
check "--target without a value is refused" bash -c '! "$1/setup.sh" --target >/dev/null 2>"$2" && grep -q "needs a value" "$2"' _ "$REPO_DIR" "$SANDBOX/err"
check "--target followed by another option is refused" bash -c '! "$1/setup.sh" --target --dry-run >/dev/null 2>&1' _ "$REPO_DIR"
check "an unknown agent is refused" bash -c '! "$1/setup.sh" --target nope >/dev/null 2>&1' _ "$REPO_DIR"
setup --target claude,opencode

echo "      -- agent picker (a terminal, a fake fzf, and the numbered prompt)"
if script --version 2>/dev/null | grep -q util-linux; then
  pk="$SANDBOX/picker"
  fakebin="$SANDBOX/fakebin"
  mkdir -p "$fakebin" "$pk"
  # A fake fzf: records its arguments and the lines it was given, then
  # "selects" the agents named in FAKE_FZF_PICK (space separated; none = empty).
  cat >"$fakebin/fzf" <<'FZF'
#!/bin/sh
printf '%s\n' "$@" >"$FAKE_FZF_LOG.args"
cat >"$FAKE_FZF_LOG.lines"
for id in $FAKE_FZF_PICK; do grep "^$id	" "$FAKE_FZF_LOG.lines"; done
exit 0
FZF
  chmod +x "$fakebin/fzf"
  # pick_run <input to type> <setup args...> — setup.sh on a terminal in its own HOME
  pick_run() {
    local input="$1"
    shift
    printf '%b' "$input" | env HOME="$pk" XDG_STATE_HOME="$pk/state" CLAUDE_SKILLS_DIR="$pk/.claude/skills" \
      OPENCODE_SKILLS_DIR="$pk/.config/opencode/skills" OPENCODE_COMMANDS_DIR="$pk/.config/opencode/commands" \
      AGENTS_SKILLS_DIR="$pk/.agents/skills" KIRO_SKILLS_DIR="$pk/.kiro/skills" \
      WINDSURF_SKILLS_DIR="$pk/.codeium/windsurf/skills" PATH="$fakebin:$PATH" TERM=xterm-256color \
      FAKE_FZF_LOG="$pk/fzf" FAKE_FZF_PICK="${FAKE_FZF_PICK:-}" AI_GENT_NO_FZF="${AI_GENT_NO_FZF:-}" \
      script -qec "$REPO_DIR/setup.sh --no-config-edits $*" /dev/null >"$SANDBOX/out" 2>&1
  }
  pk_targets="$pk/state/ai-gent/targets"

  mkdir -p "$pk/state/ai-gent"
  echo "claude codex" >"$pk_targets"
  FAKE_FZF_PICK="kiro amp" pick_run "" || true
  check "fzf: gets one line per agent, id first" test "$(wc -l <"$pk/fzf.lines")" -eq 9 -a "$(head -c 7 "$pk/fzf.lines")" == "claude$(printf '\t')"
  check "fzf: the previous choice is preselected, in order" grep -q -F 'start:pos(1)+select+pos(3)+select+first' "$pk/fzf.args"
  check "fzf: statuses are aligned" bash -c 'cut -f2 "$1" | grep -E "^.{14}  \((found|not found)\)$" | wc -l | grep -qx 9' _ "$pk/fzf.lines"
  check "fzf: what it returned is installed and remembered" test "$(cat "$pk_targets")" == "amp kiro"
  check "fzf: kiro and the shared agents got their entries" test -d "$pk/.kiro/skills" -a -d "$pk/.agents/skills"
  check "fzf: claude was not chosen, so not installed" test ! -e "$pk/.claude/skills"

  FAKE_FZF_PICK="" pick_run "" || true
  check "fzf: nothing chosen installs nothing" grep -q "no agent chosen" "$SANDBOX/out"

  echo "      -- numbered prompt"
  echo "claude codex" >"$pk_targets"
  AI_GENT_NO_FZF=1 pick_run "\n" || true
  check "numbered: Enter keeps the preselection" grep -q -F "Numbers separated by spaces [1 3]" "$SANDBOX/out"
  check "numbered: marks the preselected and shows found/not" bash -c 'grep -q "1) \[x\] Claude Code" "$1" && grep -q "2) \[ \] opencode" "$1"' _ "$SANDBOX/out"
  check "numbered: Enter remembers the preselection" test "$(cat "$pk_targets")" == "claude codex"
  AI_GENT_NO_FZF=1 pick_run "2 9\n" || true
  check "numbered: typed numbers choose the agents" test "$(cat "$pk_targets")" == "opencode windsurf"
  AI_GENT_NO_FZF=1 pick_run "1 x 99\n" || true
  check "numbered: junk is ignored, the valid number kept" bash -c 'grep -q "ignored: x" "$1" && grep -q "ignored: 99" "$1"' _ "$SANDBOX/out"
  check "numbered: and only the valid one remembered" test "$(cat "$pk_targets")" == "claude"
fi

echo "      -- default (first run, no terminal)"
d="$SANDBOX/first"
mkdir -p "$d"
env HOME="$d" XDG_STATE_HOME="$d/state" CLAUDE_SKILLS_DIR="$d/.claude/skills" \
  OPENCODE_SKILLS_DIR="$d/.config/opencode/skills" OPENCODE_COMMANDS_DIR="$d/.config/opencode/commands" \
  AGENTS_SKILLS_DIR="$d/.agents/skills" "$REPO_DIR/setup.sh" >"$SANDBOX/out" 2>&1
check "Claude Code only" bash -c 'test -L "$1/.claude/skills/qa" && test ! -e "$1/.agents" && test ! -e "$1/.config/opencode/skills"' _ "$d"
# An entry generated by an earlier setup.sh, which installed opencode by default.
mkdir -p "$d/.config/opencode/skills/project-init"
printf -- '---\nname: project-init\nmetadata:\n  source: "%s"\n---\n' "$REPO_DIR/plugins/project/skills/init/SKILL.md" \
  >"$d/.config/opencode/skills/project-init/SKILL.md"
touch "$d/.config/opencode/skills/project-init/.ai-gent-generated"
rm -rf "$d/state"
env HOME="$d" XDG_STATE_HOME="$d/state" CLAUDE_SKILLS_DIR="$d/.claude/skills" \
  OPENCODE_SKILLS_DIR="$d/.config/opencode/skills" OPENCODE_COMMANDS_DIR="$d/.config/opencode/commands" \
  "$REPO_DIR/setup.sh" --skip-prompt --no-config-edits >"$SANDBOX/out" 2>&1
check "an earlier opencode install stays chosen" test "$(cat "$d/state/ai-gent/targets")" == "claude opencode"

echo "      -- uninstall"
setup --uninstall
check "claude: no links into the repo" test "$(links_into "$CLAUDE_SKILLS_DIR" "$REPO_DIR")" -eq 0
check "opencode: no links left" test "$(links_into "$OPENCODE_SKILLS_DIR" "$REPO_DIR")" -eq 0
check "opencode: no entries or commands left" bash -c '
  ! compgen -G "$1/*/.ai-gent-generated" >/dev/null &&
  ! grep -lq "Generated by ai-gent/setup.sh" "$2"/*.md 2>/dev/null' _ "$OPENCODE_SKILLS_DIR" "$OPENCODE_COMMANDS_DIR"
check "every agent: no entries left" test "$(gen_count "$AGENTS_SKILLS_DIR")" -eq 0
check "uninstall forgets the choice" test ! -e "$targets_state"
check "user's own files kept" test -f "$CLAUDE_SKILLS_DIR/mine/SKILL.md" -a -d "$CLAUDE_SKILLS_DIR/synced/one" -a -f "$OPENCODE_COMMANDS_DIR/mine.md"

# opencode config: the V2 permission rules, the guard plugin and the skill
# denies are merged into opencode.json, and undone on --uninstall.
oc_run() { # oc_run <home> <setup.sh args...>
  local home="$1"
  shift
  env HOME="$home" XDG_STATE_HOME="$home/.local/state" \
    CLAUDE_SKILLS_DIR="$home/.claude/skills" \
    OPENCODE_SKILLS_DIR="$home/.config/opencode/skills" OPENCODE_COMMANDS_DIR="$home/.config/opencode/commands" \
    "$REPO_DIR/setup.sh" --target opencode "$@" >"$SANDBOX/out" 2>&1
}
json_get() { python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(json.dumps(eval(sys.argv[2], {"d": d})))' "$@"; }

echo "      -- opencode config"
h="$SANDBOX/oc"
mkdir -p "$h/.config/opencode"
cfg="$h/.config/opencode/opencode.json"
printf '{\n  "model": "x",\n  "permissions": [\n    { "action": "shell", "resource": "git push*", "effect": "deny" }\n  ]\n}\n' >"$cfg"
cp "$cfg" "$SANDBOX/cfg.orig"

oc_run "$h"
check "no terminal, no --yes: nothing edited" cmp -s "$SANDBOX/cfg.orig" "$cfg"
check "no terminal: the rules and plugin are printed" grep -q -F 'git commit*--no-verify*' "$SANDBOX/out"
check "no terminal: the plugin path is printed" grep -q -F 'opencode/guard' "$SANDBOX/out"

oc_run "$h" --dry-run --yes
check "--dry-run writes nothing" cmp -s "$SANDBOX/cfg.orig" "$cfg"

oc_run "$h" --yes
check "user's conflicting rule kept" test "$(json_get "$cfg" 'd["permissions"][0]["resource"]')" == '"git push*"'
check "conflict reported" grep -q -F 'git push*: yours is deny, kept' "$SANDBOX/out"
check "missing rules appended after the user's" test "$(json_get "$cfg" 'len(d["permissions"]) > 1')" == 'true'
check "a deny rule was added" test "$(json_get "$cfg" 'any(r["resource"] == "pg_restore*" for r in d["permissions"])')" == 'true'
check "read and edit denies for the credentials dir" test "$(json_get "$cfg" 'sorted(r["action"] for r in d["permissions"] if r["resource"] == "~/.config/ai-gent/*")')" == '["edit", "read"]'
check "skill denies hide the short IDs" test "$(json_get "$cfg" 'sorted(r["resource"] for r in d["permissions"] if r["action"] == "skill" and r["resource"] in ("spec", "build", "review"))')" == '["build", "review", "spec"]'
check "other settings kept" test "$(json_get "$cfg" 'd["model"]')" == '"x"'
check "a backup was kept" bash -c 'compgen -G "$1.bak-*" >/dev/null' _ "$cfg"
check "the guard plugin is registered" test "$(json_get "$cfg" 'd["plugins"]')" == '["'"$REPO_DIR"'/opencode/guard"]'

cp "$cfg" "$SANDBOX/cfg.merged"
oc_run "$h" --yes
check "re-run: idempotent" cmp -s "$SANDBOX/cfg.merged" "$cfg"
check "re-run: reports ok" grep -Eq '^\[ok\] +opencode guard rules and plugin$' "$SANDBOX/out"

oc_run "$h" --uninstall
check "uninstall: only the added rules removed" test "$(json_get "$cfg" 'd')" == '{"model": "x", "permissions": [{"action": "shell", "resource": "git push*", "effect": "deny"}]}'
rm -f "$cfg".bak-*

printf '{\n  // mine\n  "model": "x"\n}\n' >"$cfg"
cp "$cfg" "$SANDBOX/cfg.jsonc"
oc_run "$h" --yes
check "a file with comments is left alone, snippet printed" cmp -s "$SANDBOX/cfg.jsonc" "$cfg"
check "a file with comments: snippet printed" grep -q -F 'has comments' "$SANDBOX/out"

printf '{ "permissions": "ask" }\n' >"$cfg"
oc_run "$h" --yes
check "a non-array permissions is left alone" test "$(json_get "$cfg" 'd')" == '{"permissions": "ask"}'

rm -f "$cfg"
oc_run "$h" --yes
check "no config: created with the rules" test "$(json_get "$cfg" 'any(r["resource"] == "pg_restore*" for r in d["permissions"])')" == 'true'
check "no config: created with the plugin" test "$(json_get "$cfg" 'd["plugins"]')" == '["'"$REPO_DIR"'/opencode/guard"]'
oc_run "$h" --uninstall
check "uninstall: a created, untouched config is removed" test ! -e "$cfg"

echo "      -- install.sh (clone, then update)"
AI_GENT_REPO="$REPO_DIR" sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1 || cat "$SANDBOX/out"
clone="$HOME/.local/share/ai-gent"
check "clones into the default directory" test -f "$clone/setup.sh"
cloned=$(count "$clone/skills" "$clone/plugins" -mindepth 1 -maxdepth 1 -type d)
check "links point into the clone" test "$(links_into "$CLAUDE_SKILLS_DIR" "$clone")" -eq "$cloned"
AI_GENT_REPO="$REPO_DIR" sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1
check "re-run updates in place" grep -q "updating $clone" "$SANDBOX/out"
echo "local change" >>"$clone/README.md"
AI_GENT_REPO="$REPO_DIR" sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1
check "local changes are left alone" grep -q "local changes" "$SANDBOX/out"
mkdir -p "$SANDBOX/not-a-clone"
check "refuses a non-clone directory" bash -c '! AI_GENT_DIR="$1" AI_GENT_REPO="$2" sh "$2/install.sh" >/dev/null 2>&1' _ "$SANDBOX/not-a-clone" "$REPO_DIR"

echo "      -- install.sh (pin a tag, then move the pin)"
src="$SANDBOX/src"
pinned="$SANDBOX/pinned"
g() { git -C "$src" -c user.name=test -c user.email=test@example.test "$@"; }
git clone -q "$REPO_DIR" "$src"
# Annotated tags on their own commits, like real releases (describe prefers
# annotated tags, so sharing a commit with the repo's own tags would be ambiguous).
g commit -q --allow-empty -m "chore: release 9.9.0"
g tag -a 9.9.0 -m 9.9.0
g commit -q --allow-empty -m "chore: release 9.9.1"
g tag -a 9.9.1 -m 9.9.1
AI_GENT_DIR="$pinned" AI_GENT_REPO="$src" AI_GENT_BRANCH=9.9.0 sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1
check "clones at the tag" test "$(git -C "$pinned" rev-parse HEAD)" == "$(g rev-parse '9.9.0^{commit}')"
AI_GENT_DIR="$pinned" AI_GENT_REPO="$src" sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1
check "stays pinned without AI_GENT_BRANCH" grep -q "pinned to 9.9.0" "$SANDBOX/out"
AI_GENT_DIR="$pinned" AI_GENT_REPO="$src" AI_GENT_BRANCH=9.9.1 sh "$REPO_DIR/install.sh" --target claude >"$SANDBOX/out" 2>&1
check "moves the pin to a newer tag" test "$(git -C "$pinned" rev-parse HEAD)" == "$(g rev-parse '9.9.1^{commit}')"

exit $((failures > 0))
